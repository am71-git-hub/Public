#!/usr/bin/env python3
"""Build the G1 study site and the generated markdown files.

Reads data/ and the hand-written guides, then writes:
  site/index.html                one self-contained page (CSS, JS, data and pictures inlined)
  site/g1-practice-no-save.html  the same page in no-save mode (nothing stored in the browser)
  signs/guide/S*.md              sign study guides (from data/signs.json)
  rules/guide/R0-numbers.md      numbers cheat sheet (from data/numbers.json)
  signs/questions/*.md           question bank, answers hidden in <details>
  rules/questions/*.md
  signs/README.md, rules/README.md

Run from anywhere:  python3 build.py   (standard library only)
"""
import base64
import hashlib
import html
import json
import os
import random
import re
import sys
from datetime import date

ROOT = os.path.dirname(os.path.abspath(__file__))
PER_TYPE = 60

HALVES = {
    "signs": {"title": "Signs", "icon": "🚸", "desc": "Road signs, traffic lights, pedestrian signals and pavement markings."},
    "rules": {"title": "Rules", "icon": "📘", "desc": "Licensing, demerit points, right-of-way, stopping, parking, safe driving and more."},
}
TYPES = {
    "signs": [
        ("meaning", "Sign meaning", "Picture → what it means"),
        ("pick", "Pick the sign", "Meaning → choose the right picture"),
        ("lookalike", "Look-alikes", "Signs, lights and lines that are easy to mix up"),
        ("shape", "Shapes & colours", "What the shape or colour tells you"),
        ("action", "What do you do?", "What you must do when you see it"),
    ],
    "rules": [
        ("numbers", "Exact numbers", "Metres, points, days, dollars, km/h, alcohol"),
        ("row", "Right-of-way", "Who goes first"),
        ("trap", "Word traps", "NOT / EXCEPT / ALWAYS / NEVER / FIRST"),
        ("best", "Best action", "What to do in a situation"),
        ("law", "Laws & consequences", "What's required, and what happens if you don't"),
    ],
}
# id, half, file slug. Titles come from data/signs.json (signs) or each guide's first heading (rules).
CATS = [
    ("S1", "signs", "shapes-colours"), ("S2", "signs", "regulatory-hov"), ("S3", "signs", "warning"),
    ("S4", "signs", "temporary-construction"), ("S5", "signs", "information-other"),
    ("S6", "signs", "traffic-lights"), ("S7", "signs", "pedestrian-signals-markings"),
    ("R0", "rules", "numbers"), ("R1", "rules", "licensing"), ("R2", "rules", "demerit-points"),
    ("R3", "rules", "suspensions-alcohol-drugs"), ("R4", "rules", "intersections-right-of-way"),
    ("R5", "rules", "stopping"), ("R6", "rules", "turns-lanes-passing"), ("R7", "rules", "sharing-the-road"),
    ("R8", "rules", "speed-and-space"), ("R9", "rules", "parking"), ("R10", "rules", "freeway-hov"),
    ("R11", "rules", "night-weather-emergencies"), ("R12", "rules", "safe-driving"),
    ("R13", "rules", "vehicle-insurance-towing"),
]
SLUG = {c: s for c, _, s in CATS}
HALF_OF = {c: h for c, h, _ in CATS}
GENERATED = "<!-- Generated by build.py. Edit data/ or the guide files instead, then run: python3 build.py -->\n"

problems = []


def path(*parts):
    return os.path.join(ROOT, *parts)


def read(rel):
    with open(path(rel), encoding="utf-8") as f:
        return f.read()


def write(rel, text):
    os.makedirs(os.path.dirname(path(rel)), exist_ok=True)
    with open(path(rel), "w", encoding="utf-8") as f:
        f.write(text)


def guide_file(cid):
    return f"{HALF_OF[cid]}/guide/{cid}-{SLUG[cid]}.md"


def questions_file(cid):
    return f"{HALF_OF[cid]}/questions/{cid}-{SLUG[cid]}.md"


# ---------------------------------------------------------------- questions

def load_questions():
    type_keys = {h: [t[0] for t in TYPES[h]] for h in TYPES}
    out, seen_ids = [], set()
    for cid, half, _ in CATS:
        qpath = f"data/questions/{cid}.json"
        if not os.path.exists(path(qpath)):
            continue
        texts = set()
        for n, raw in enumerate(json.loads(read(qpath)), 1):
            where = f"{cid} #{n}"
            for field in ("t", "q", "a", "w", "e", "s"):
                if field not in raw:
                    problems.append(f"{where}: missing '{field}'")
            if any(f not in raw for f in ("t", "q", "a", "w")):
                continue
            if raw["t"] not in type_keys[half]:
                problems.append(f"{where}: type '{raw['t']}' is not a {half} type")
            if len(raw["w"]) != 3:
                problems.append(f"{where}: needs exactly 3 wrong answers")
            choices = [raw["a"]] + list(raw["w"])
            if len(set(choices)) != len(choices):
                problems.append(f"{where}: choices are not all different")
            key = (raw["q"], raw.get("img"), raw["a"])
            if key in texts:
                problems.append(f"{where}: duplicate question")
            texts.add(key)
            pics = [raw["img"]] if raw.get("img") else []
            if raw["t"] == "pick":
                pics += choices
            for p in pics:
                if not os.path.exists(path("img", p)):
                    problems.append(f"{where}: missing picture img/{p}")
            qid = cid + "-" + hashlib.sha1("|".join([raw["q"], raw.get("img") or "", raw["a"]]).encode()).hexdigest()[:6]
            if qid in seen_ids:
                problems.append(f"{where}: id clash {qid}")
            seen_ids.add(qid)
            order = list(range(len(choices)))
            random.Random(qid).shuffle(order)
            out.append({
                "id": qid, "cat": cid, "half": half, "type": raw["t"], "q": raw["q"],
                "img": raw.get("img"), "c": [choices[i] for i in order], "ans": order.index(0),
                "e": raw.get("e", ""), "s": raw.get("s", ""), "o": bool(raw.get("o")),
                "f": raw.get("f", "handbook"),
            })
    return out


def balance_report(questions):
    ok = True
    for half in ("signs", "rules"):
        counts = {t: 0 for t, _, _ in TYPES[half]}
        for q in questions:
            if q["half"] == half and not q["o"]:
                counts[q["type"]] += 1
        line = "  ".join(f"{t} {n}" for t, n in counts.items())
        total = sum(counts.values())
        flag = "" if all(n == PER_TYPE for n in counts.values()) else f"   <- not {PER_TYPE} each"
        ok = ok and not flag
        print(f"  {HALVES[half]['title']:<6} {line}  = {total}{flag}")
    print(f"  Official MTO samples: {sum(q['o'] for q in questions)}")
    return ok


# ---------------------------------------------------------------- markdown → HTML (small fixed subset)

IMG_RE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)")
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def img_key(src, md_rel):
    """Turn a markdown image path into a key like 'signs/3-1-5.jpg' (relative to img/)."""
    full = os.path.normpath(os.path.join(os.path.dirname(path(md_rel)), src))
    key = os.path.relpath(full, path("img")).replace(os.sep, "/")
    if key.startswith("..") or not os.path.exists(full):
        problems.append(f"{md_rel}: picture not found: {src}")
    return key


def link_target(href, md_rel):
    """Map a markdown link to an in-app route, or keep it as an outside link."""
    if re.match(r"https?://", href):
        return href, True
    full = os.path.normpath(os.path.join(os.path.dirname(path(md_rel)), href.split("#")[0]))
    rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
    m = re.match(r"(signs|rules)/(guide|questions)/([SR]\d+)-", rel)
    if m:
        return ("#/guide/" if m.group(2) == "guide" else "#/topic/") + m.group(3), False
    m = re.match(r"(signs|rules)/README\.md$", rel)
    if m:
        return "#/half/" + m.group(1), False
    if rel == "test-day.md":
        return "#/page/testday", False
    return None, False


def inline(text, md_rel, images):
    """Escape, then apply images, links, bold, italics and code."""
    parts, pos = [], 0
    for m in IMG_RE.finditer(text):
        parts.append(("t", text[pos:m.start()]))
        parts.append(("i", m))
        pos = m.end()
    parts.append(("t", text[pos:]))
    out = []
    for kind, val in parts:
        if kind == "i":
            key = img_key(val.group(2), md_rel)
            images.add(key)
            out.append(f'<img data-img="{html.escape(key)}" alt="{html.escape(val.group(1))}">')
            continue
        s = html.escape(val, quote=False)

        def link(m):
            target, outside = link_target(html.unescape(m.group(2)), md_rel)
            if not target:
                return m.group(1)
            extra = ' target="_blank" rel="noopener"' if outside else ""
            return f'<a href="{html.escape(target)}"{extra}>{m.group(1)}</a>'

        s = LINK_RE.sub(link, s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        out.append(s)
    return "".join(out)


def md_to_html(md, md_rel, images):
    lines = md.replace("\r", "").split("\n")
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.startswith("<!--"):
            i += 1
            continue
        m = re.match(r"(#{1,4}) (.*)", line)
        if m:
            lvl = len(m.group(1))
            out.append(f"<h{lvl}>{inline(m.group(2), md_rel, images)}</h{lvl}>")
            i += 1
            continue
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], [r for r in rows[1:] if not re.match(r"^:?-+:?$", r[0] or "-")]
            t = ["<div class='tablewrap'><table><thead><tr>"]
            t += [f"<th>{inline(c, md_rel, images)}</th>" for c in head]
            t.append("</tr></thead><tbody>")
            for r in body:
                t.append("<tr>" + "".join(f"<td>{inline(c, md_rel, images)}</td>" for c in r) + "</tr>")
            t.append("</tbody></table></div>")
            out.append("".join(t))
            continue
        if line.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].startswith(">"):
                quote.append(lines[i].lstrip(">").strip())
                i += 1
            out.append(f"<blockquote><p>{inline(' '.join(quote), md_rel, images)}</p></blockquote>")
            continue
        if re.match(r"\s*- ", line) or re.match(r"\d+\. ", line):
            ordered = bool(re.match(r"\d+\. ", line))
            tag = "ol" if ordered else "ul"
            items = []
            while i < len(lines) and (re.match(r"\s*- ", lines[i]) or re.match(r"\d+\. ", lines[i])):
                cur = lines[i]
                if cur.startswith("  ") and items:
                    items[-1][1].append(re.sub(r"^\s*- ", "", cur))
                else:
                    items.append([re.sub(r"^(- |\d+\. )", "", cur), []])
                i += 1
            h = [f"<{tag}>"]
            for text, subs in items:
                h.append(f"<li>{inline(text, md_rel, images)}")
                if subs:
                    h.append("<ul>" + "".join(f"<li>{inline(s, md_rel, images)}</li>" for s in subs) + "</ul>")
                h.append("</li>")
            h.append(f"</{tag}>")
            out.append("".join(h))
            continue
        if IMG_RE.fullmatch(line.strip()):
            out.append(f"<figure>{inline(line.strip(), md_rel, images)}</figure>")
            i += 1
            continue
        para = []
        while (i < len(lines) and lines[i].strip() and not IMG_RE.fullmatch(lines[i].strip())
               and not re.match(r"(#{1,4} |\||>|\s*- |\d+\. )", lines[i])):
            para.append(lines[i].strip())
            i += 1
        out.append(f"<p>{inline(' '.join(para), md_rel, images)}</p>")
    return "\n".join(out)


# ---------------------------------------------------------------- generated markdown

def esc_cell(text):
    return text.replace("|", "\\|")


def sign_guides(signs):
    for c in signs["cats"]:
        cid = c["id"]
        md = [GENERATED, f"# {cid} · {c['title']}\n",
              f"**Signs half** · [Back to Signs](../README.md) · [Quiz: {cid} questions](../questions/{cid}-{SLUG[cid]}.md)\n",
              "## Key points"]
        md += [f"- {b}" for b in c["intro"]]
        md += ["", f"## The {len(c['signs'])} pictures", "| Picture | What it means |", "|---|---|"]
        for s in c["signs"]:
            if s["meaning"].rstrip(". ").lower() == s["name"].lower():
                meaning = f"**{esc_cell(s['meaning'])}**"
            else:
                meaning = f"**{esc_cell(s['name'])}.** {esc_cell(s['meaning'])}"
            if s.get("do"):
                meaning += f" **Do:** {esc_cell(s['do'])}"
            md.append(f"| ![{esc_cell(s['name'])}](../../img/{s['file']}) | {meaning} |")
        md += ["", "## Memory tricks"] + [f"- {t}" for t in c["tips"]]
        write(guide_file(cid), "\n".join(md) + "\n")


def numbers_guide(nums):
    md = [GENERATED, f"# {nums['title']}\n",
          "**Rules half** · [Back to Rules](../README.md) · Flashcards for these are in the web app (Rules → Flashcards)\n"]
    md += [f"- {b}" for b in nums["intro"]]
    for g in nums["groups"]:
        md += ["", f"## {g['title']}", "| Number | What it's for | Topic |", "|---|---|---|"]
        for f in g["facts"]:
            topic = f"[{f['cat']}]({f['cat']}-{SLUG[f['cat']]}.md)"
            md.append(f"| **{esc_cell(f['value'])}** | {esc_cell(f['fact'])} | {topic} |")
    md += ["", "## Easy to mix up", "| Numbers | How to keep them straight |", "|---|---|"]
    md += [f"| **{esc_cell(m['pair'])}** | {esc_cell(m['tip'])} |" for m in nums["mixups"]]
    md += ["", "## Memory tricks"] + [f"- {t}" for t in nums["tricks"]]
    write(guide_file("R0"), "\n".join(md) + "\n")


def question_pages(questions, titles):
    type_label = {t: label for h in TYPES for t, label, _ in TYPES[h]}
    for cid, half, _ in CATS:
        qs = [q for q in questions if q["cat"] == cid]
        if not qs:
            continue
        md = [GENERATED, f"# {cid} · {titles[cid]}: questions\n",
              f"**{HALVES[half]['title']} half** · {len(qs)} questions · "
              f"[Study guide](../guide/{cid}-{SLUG[cid]}.md) · [All {half} topics](../README.md)\n",
              "Answers are hidden. Tap **Answer** under each question to check yourself.\n"]
        for n, q in enumerate(qs, 1):
            star = " ⭐ *Official MTO sample question*" if q["o"] else ""
            md += ["---", "", f"### {n}. {q['q']}", "", f"*{type_label[q['type']]}*{star}", ""]
            if q["img"]:
                md += [f"![picture](../../img/{q['img']})", ""]
            letters = "ABCD"
            if q["type"] == "pick":
                md += ["| " + " | ".join(letters) + " |", "|---|---|---|---|",
                       "| " + " | ".join(f"![{l}](../../img/{c})" for l, c in zip(letters, q["c"])) + " |", ""]
            else:
                md += [f"- **{l}.** {c}" for l, c in zip(letters, q["c"])] + [""]
            right = letters[q["ans"]]
            answer = f"**{right}**" if q["type"] == "pick" else f"**{right}. {q['c'][q['ans']]}**"
            source = "ontario.ca" if q["f"] == "ontario.ca" else "Handbook"
            md += ["<details><summary>Answer</summary>", "", answer, "", q["e"], "",
                   f"> 📖 {source}: \"{q['s']}\"", "", "</details>", ""]
        write(questions_file(cid), "\n".join(md))


def half_readmes(questions, titles, signs):
    for half in ("signs", "rules"):
        type_label = TYPES[half]
        n_half = sum(1 for q in questions if q["half"] == half)
        md = [GENERATED, f"# {HALVES[half]['icon']} {HALVES[half]['title']} half\n",
              f"{HALVES[half]['desc']}\n",
              f"On the real test this is **20 questions**, and you need **16 right** to pass this half. "
              f"This bank has **{n_half}** questions for it.\n",
              "[← Back to the start page](../README.md)\n",
              "## Topics", "| Topic | Study guide | Questions |", "|---|---|---|"]
        for cid, h, _ in CATS:
            if h != half:
                continue
            n = sum(1 for q in questions if q["cat"] == cid)
            qcell = f"[{n} questions](questions/{cid}-{SLUG[cid]}.md)" if n else "Flashcards in the web app"
            md.append(f"| **{cid}** · {titles[cid]} | [Guide](guide/{cid}-{SLUG[cid]}.md) | {qcell} |")
        md += ["", f"## Question types (every type gets equal weight: {PER_TYPE} each)"]
        md += [f"- **{label}**: {desc}" for _, label, desc in type_label]
        if half == "signs":
            md += ["", f"Every one of the **{sum(len(c['signs']) for c in signs['cats'])} pictures** in the handbook's "
                   "signs, lights and markings chapters is in the guides and is used in at least one question."]
        write(f"{half}/README.md", "\n".join(md) + "\n")


# ---------------------------------------------------------------- site

def data_uri(key):
    with open(path("img", key), "rb") as f:
        return "data:image/jpeg;base64," + base64.b64encode(f.read()).decode()


def build_site(questions, signs, nums, titles):
    images = set()
    cats = []
    for cid, half, _ in CATS:
        rel = guide_file(cid)
        guide = md_to_html(read(rel), rel, images)
        n = sum(1 for q in questions if q["cat"] == cid)
        cats.append({"id": cid, "half": half, "title": titles[cid], "n": n, "guide": guide})
    pages = []
    for pid, rel, title in (("testday", "test-day.md", "Test day"),):
        pages.append({"id": pid, "title": title, "html": md_to_html(read(rel), rel, images)})
    flash = {"signs": [], "rules": []}
    for c in signs["cats"]:
        for s in c["signs"]:
            images.add(s["file"])
            flash["signs"].append({"img": s["file"], "name": s["name"], "meaning": s["meaning"],
                                   "do": s.get("do", ""), "cat": c["id"]})
    for g in nums["groups"]:
        for f in g["facts"]:
            flash["rules"].append({"front": f["fact"], "back": f["value"], "cat": f["cat"], "group": g["title"]})
    for q in questions:
        if q["img"]:
            images.add(q["img"])
        if q["type"] == "pick":
            images.update(q["c"])
    data = {
        "built": date.today().isoformat(),
        "halves": HALVES,
        "types": {h: [{"key": k, "label": l, "desc": d} for k, l, d in TYPES[h]] for h in TYPES},
        "cats": cats, "pages": pages, "questions": questions, "flash": flash,
        "images": {k: data_uri(k) for k in sorted(images)},
    }
    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    page = read("app/template.html")
    page = page.replace("/*__CSS__*/", read("app/style.css"))
    page = page.replace("/*__DATA__*/", "window.G1 = " + blob + ";")
    page = page.replace("/*__APP__*/", read("app/app.js"))
    write("site/index.html", page)
    nosave = page.replace("window.G1 = ", "window.G1_NOSAVE = true;\nwindow.G1 = ", 1)
    nosave = nosave.replace("<title>G1 Practice</title>", "<title>G1 Practice (no save)</title>", 1)
    write("site/g1-practice-no-save.html", nosave)
    return len(page.encode()), images


def main():
    signs = json.loads(read("data/signs.json"))
    nums = json.loads(read("data/numbers.json"))
    questions = load_questions()

    titles = {c["id"]: c["title"] for c in signs["cats"]}
    titles["R0"] = nums["title"].split(" · ", 1)[1]
    for cid, half, _ in CATS:
        if half == "rules" and cid != "R0":
            first = read(guide_file(cid)).split("\n", 1)[0]
            titles[cid] = first.lstrip("# ").split(" · ", 1)[1]

    sign_files = {s["file"] for c in signs["cats"] for s in c["signs"]}
    used = set()
    for q in questions:
        if q["img"]:
            used.add(q["img"])
        if q["type"] == "pick":
            used.update(q["c"])
    unused = sorted(sign_files - used)
    if unused:
        problems.append("pictures not used in any question: " + ", ".join(unused))

    sign_guides(signs)
    numbers_guide(nums)
    question_pages(questions, titles)
    half_readmes(questions, titles, signs)
    size, images = build_site(questions, signs, nums, titles)

    print(f"Questions: {len(questions)}")
    balanced = balance_report(questions)
    print(f"  Sign pictures used in questions: {len(sign_files & used)}/{len(sign_files)}")
    print(f"  Pictures inlined in the page: {len(images)}")
    print(f"Wrote site/index.html ({size / 1_000_000:.1f} MB), guides and question pages.")
    if not balanced:
        print("Note: question types are not exactly balanced (the app still mixes types evenly).")
    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print("  -", p)
        sys.exit(1)
    print("0 problems.")


if __name__ == "__main__":
    main()
